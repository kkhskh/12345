"""Write audits/provenance_inventory.md and RELEASE_MANIFEST.json.

Usage (from the package root):
    python scripts/build_release_manifest.py

The provenance inventory is generated from data/provenance_manifest.json, so no hash in it is
typed by hand. The release manifest lists every package file outside logs/ with its size,
SHA-256, pipeline layer and role. logs/ is excluded because each log records its own hashes
and later commands add logs. Run this last; scripts/cross_artifact_check.py verifies it.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PKG / "scripts"))
import cross_artifact_check as cac  # noqa: E402

ROLES = [
    ("data/raw/", "A", "saved result arrays and tables copied byte-for-byte from the original run archives"),
    ("data/archival/", "A", "verbatim console excerpts and the archival value register"),
    ("data/protocols/", "A", "preregistrations and run configurations copied from the project repository"),
    ("data/", "A", "data documentation and provenance manifest"),
    ("scripts/p1lib.py", "B", "analysis library"),
    ("scripts/recompute_analysis.py", "B", "recomputation entry point"),
    ("analysis/", "B", "recomputed analysis outputs"),
    ("scripts/reproduce_tables.py", "C", "table generator"),
    ("tables/", "C", "generated tables"),
    ("scripts/reproduce_figures.py", "C", "figure generator"),
    ("figures/", "C", "generated figures and figure provenance"),
    ("scripts/verify_paper_claims.py", "D", "claim verifier"),
    ("audits/claim_evidence_ledger.csv", "D", "claim-evidence ledger read by the verifier"),
    ("verification/", "D", "independent re-derivation sharing no code with the analysis library"),
    ("tests/", "D", "package tests"),
    ("scripts/cross_artifact_check.py", "D", "cross-artifact consistency check"),
    ("scripts/build_pdf.py", "E", "manuscript builder"),
    ("manuscript/", "E", "manuscript source, generated TeX and PDF, bibliography"),
    ("scripts/", "tooling", "logging, release and development tooling"),
    ("audits/", "review", "audit reports"),
    ("reviews/", "review", "adversarial reviews and responses"),
    ("", "documentation", "package documentation"),
]


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def role(rel: str) -> tuple[str, str]:
    for prefix, layer, desc in ROLES:
        if rel.startswith(prefix):
            return layer, desc
    raise AssertionError(rel)


def inventory() -> str:
    m = json.loads((PKG / "data" / "provenance_manifest.json").read_text(encoding="utf-8"))
    out = ["# Provenance inventory", "",
           "Generated by `scripts/build_release_manifest.py` from `data/provenance_manifest.json`. Do not edit by hand.", "",
           f"Manifest generated {m['generated_utc']}. Policy: {m['policy']}", "",
           "## Result archives (evidence level RECOMPUTED)", "",
           "| Study | Original archive | Archive SHA-256 | Bytes | Members copied |", "|---|---|---|---|---|"]
    for k, a in m["archives"].items():
        out.append(f"| {k} | `{Path(a['original_path']).name}` | `{a['archive_sha256']}` | {a['archive_bytes']} | {len(a['members'])} |")
    out += ["", "Every copied member, with its package path and SHA-256:", "",
            "| Package path | SHA-256 | Bytes |", "|---|---|---|"]
    for a in m["archives"].values():
        for e in a["members"]:
            out.append(f"| `{e['package_path']}` | `{e['sha256']}` | {e['bytes']} |")
    out += ["", "## Secondary archives (cross-checks only, not copied)", "",
            "| Name | Original archive | Archive SHA-256 |", "|---|---|---|"]
    for k, a in m["secondary_archives"].items():
        out.append(f"| {k} | `{Path(a['original_path']).name}` | `{a['archive_sha256']}` |")
    out += ["", "## Protocols and configurations (evidence level PROTOCOL)", "",
            "| Package path | Repository path | SHA-256 | Git blob |", "|---|---|---|---|"]
    for e in m["protocols"]:
        out.append(f"| `{e['package_path']}` | `{e['repo_path']}` | `{e['sha256']}` | `{e.get('git_blob')}` |")
    out += ["", "## Console excerpts (evidence level ARCHIVAL)", "",
            "| Package path | SHA-256 | Description |", "|---|---|---|"]
    for e in m["console_excerpts"]:
        out.append(f"| `{e['package_path']}` | `{e['sha256']}` | {e['description']} |")
    out += ["", "## Searched for and not found", "", "| Item | Expected | Result |", "|---|---|---|"]
    for e in m["not_found"]:
        out.append(f"| {e['item']} | `{e['expected']}` | {e['result']} |")
    return "\n".join(out) + "\n"


def main() -> int:
    (PKG / "audits" / "provenance_inventory.md").write_text(inventory(), encoding="utf-8")
    files = []
    for p in cac.release_files():
        rel = str(p.relative_to(PKG))
        layer, desc = role(rel)
        files.append({"path": rel, "bytes": p.stat().st_size, "sha256": sha256(p), "layer": layer, "role": desc})
    man = {
        "package": "Causal Information Outside a Frozen Board Probe in Othello-GPT: private review package",
        "layers": {"A": "raw data", "B": "analysis", "C": "tables and figures", "D": "verification", "E": "manuscript build"},
        "excluded": "logs/ (each log records its own hashes), __pycache__, .DS_Store, this file",
        "not_included": ["model checkpoint", "probe weights", "sealed confirmation protocol and data"],
        "files": files,
    }
    (PKG / "RELEASE_MANIFEST.json").write_text(json.dumps(man, indent=1) + "\n", encoding="utf-8")
    print(f"wrote audits/provenance_inventory.md and RELEASE_MANIFEST.json ({len(files)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
