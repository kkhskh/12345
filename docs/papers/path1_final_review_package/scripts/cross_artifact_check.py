"""Cross-artifact consistency: Markdown, TeX, PDF, documentation, verdict and release manifest agree.

Usage (from anywhere):
    python scripts/cross_artifact_check.py              # all checks that need only the package
    python scripts/cross_artifact_check.py --pdf-text   # also extract the PDF text (needs pymupdf)

Checks:
  1. paper_master.tex is exactly what scripts/build_pdf.py generates from the current paper_master.md.
  2. The build record ties the current .md, .tex, .pdf and figure files together.
  3. With --pdf-text: every heading, figure caption, table caption and official letter of the
     Markdown appears in the PDF text, and the PDF embeds one image per manuscript figure.
  4. Every script, test and file path named in README.md, REPRODUCIBILITY.md and data/README.md exists.
  5. FINAL_SCIENTIFIC_VERDICT.md has exactly one "**Verdict:**" line naming one of the six Path 1
     verdicts, README.md names that verdict and no other, and the
     verdict file carries every official result letter verbatim.
  6. Every number in the prose of README.md and FINAL_SCIENTIFIC_VERDICT.md occurs in the manuscript.
  7. All four studies record the same checkpoint and probe hashes, and data/README.md states them.
  8. RELEASE_MANIFEST.json lists every package file outside logs/ with its current SHA-256.
Exit code 1 if any check fails. It never writes inside the package.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_pdf  # noqa: E402
import verify_paper_claims as vpc  # noqa: E402

PKG = Path(__file__).resolve().parents[1]
MS = PKG / "manuscript"
VERDICTS = (
    "PATH1_COMPLETE_READY_FOR_INDEPENDENT_HUMAN_REVIEW",
    "PATH1_COMPLETED_WITH_EXPLICIT_EXTERNAL_VERIFICATION_LIMITATIONS",
    "PATH1_SCIENTIFIC_EVIDENCE_BLOCKED",
    "PATH1_REPRODUCIBILITY_FAILED",
    "PATH1_MANUSCRIPT_OR_FIGURES_INCOMPLETE",
    "PATH1_NOVELTY_NOT_ESTABLISHED",
)
DOCS = ("README.md", "REPRODUCIBILITY.md", "data/README.md")
MANIFEST_EXCLUDE = {"RELEASE_MANIFEST.json"}

passes: list[str] = []
failures: list[str] = []


def check(ok: bool, name: str, detail: str = "") -> None:
    (passes if ok else failures).append(name if ok else f"{name}: {detail}")


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def release_files() -> list[Path]:
    return sorted(p for p in PKG.rglob("*") if p.is_file() and p.relative_to(PKG).parts[0] != "logs"
                  and "__pycache__" not in p.parts and p.name != ".DS_Store" and p.name not in MANIFEST_EXCLUDE)


def tex_and_build() -> None:
    md_path, tex_path, pdf_path = MS / "paper_master.md", MS / "paper_master.tex", MS / "paper_master.pdf"
    md_sha = sha256(md_path)
    expected = (f"% Generated by scripts/build_pdf.py from paper_master.md (sha256 {md_sha}). Do not edit.\n"
                + build_pdf.convert(md_path.read_text(encoding="utf-8")))
    check(tex_path.read_text(encoding="utf-8") == expected, "paper_master.tex is the exact conversion of the current paper_master.md")
    rec = json.loads((MS / "build_record.json").read_text(encoding="utf-8"))
    check(rec["md_sha256"] == md_sha and rec["tex_sha256"] == sha256(tex_path) and rec["pdf_sha256"] == sha256(pdf_path),
          "build record matches the current .md, .tex and .pdf")
    figs = {p.name: sha256(p) for p in sorted((PKG / "figures").glob("*.pdf"))}
    check(rec["figures_sha256"] == figs, "PDF was compiled from the current figure files", "rerun scripts/build_pdf.py")


def norm(s: str) -> str:
    s = re.sub(r"\\\(|\\\)|\*|`|\\", "", s)
    s = s.replace("\u2014", "-").replace("\u2013", "-").replace("\u2212", "-")
    return re.sub(r"[^0-9A-Za-z]+", "", s).lower()


def pdf_text() -> None:
    try:
        import fitz  # pymupdf
    except ImportError:
        check(False, "PDF text extraction", "--pdf-text needs pymupdf (pip install pymupdf)")
        return
    md = (MS / "paper_master.md").read_text(encoding="utf-8")
    doc = fitz.open(MS / "paper_master.pdf")
    text = norm(" ".join(page.get_text() for page in doc))
    images = sum(len(page.get_images(full=True)) for page in doc)
    xobjects = sum(len(page.get_xobjects()) for page in doc)
    heads = [re.sub(r"^#+\s+(Appendix [A-Z]\.\s+)?", "", l) for l in md.splitlines() if l.startswith("#")]
    for h in heads:
        check(norm(h) in text, f"PDF contains heading: {h}")
    caps = re.findall(r"^!\[(Figure \d+\.[^\]]*)\]", md, flags=re.M) + re.findall(r"^Table: (Table \d+\.[^\n]*)", md, flags=re.M)
    for c in caps:
        words = re.sub(r"\\\(.*?\\\)", " ", c.split(". ", 1)[1]).split()[:6]
        check(norm(" ".join(words)) in text, f"PDF contains caption start: {c[:40]}")
    for L in vpc.LETTERS:
        check(norm(L) in text, f"PDF contains letter: {L}")
    nfig = len(re.findall(r"^!\[Figure", md, flags=re.M))
    check(images + xobjects >= nfig, f"PDF embeds at least {nfig} figure objects", f"{images} images, {xobjects} form xobjects")
    print(f"PDF: {doc.page_count} pages, {images} images, {xobjects} form xobjects")


def docs() -> None:
    for d in DOCS:
        p = PKG / d
        check(p.is_file(), f"{d} exists")
        if not p.is_file():
            continue
        t = p.read_text(encoding="utf-8")
        named = set(re.findall(r"(?<![\w./-])((?:scripts|tests|verification|manuscript|figures|tables|data|analysis|audits|reviews|logs)/[\w./*-]*[\w*])", t))
        missing = sorted(n for n in named if not ((PKG / n).exists() if "*" not in n else list(PKG.glob(n))))
        check(not missing, f"every package path named in {d} exists", str(missing))


def verdict() -> None:
    v = (PKG / "FINAL_SCIENTIFIC_VERDICT.md").read_text(encoding="utf-8")
    r = (PKG / "README.md").read_text(encoding="utf-8")
    stated = re.findall(r"^\*\*Verdict:\*\* `([A-Z0-9_]+)`$", v, flags=re.M)
    check(len(stated) == 1 and stated[0] in VERDICTS, "FINAL_SCIENTIFIC_VERDICT.md states exactly one Path 1 verdict", str(stated))
    in_r = [x for x in VERDICTS if x in r]
    check(in_r == stated[:1], "README.md names the same Path 1 verdict and no other", f"{stated} vs {in_r}")
    for L in vpc.LETTERS:
        check(f"`{L}`" in v, f"verdict file carries letter verbatim: {L}")


def prose_numbers() -> None:
    md = (MS / "paper_master.md").read_text(encoding="utf-8")
    md_tokens = {t for t in vpc.TOKEN_RE.findall(md)}
    for d in ("README.md", "FINAL_SCIENTIFIC_VERDICT.md"):
        t = (PKG / d).read_text(encoding="utf-8")
        t = re.sub(r"```.*?```", " ", t, flags=re.S)
        t = re.sub(r"`[^`]*`", " ", t)
        t = re.sub(r"\[[^\]]*\]\([^)]*\)", " ", t)
        t = re.sub(r"\b[\w-]+(/[\w.-]+)+", " ", t)
        t = re.sub(r"\b(Figure|Table|Appendix|Stage|Section|Python|item)\s+\d+", " ", t)
        t = re.sub(r"(?m)^#+.*$", " ", t)
        extra = sorted({tok for tok in vpc.TOKEN_RE.findall(t)} - md_tokens)
        check(not extra, f"every number in the prose of {d} occurs in the manuscript", str(extra))


def dependencies() -> None:
    deps = {p.parent.name: json.loads(p.read_text(encoding="utf-8")) for p in sorted((PKG / "data" / "raw").glob("*/*dependency_manifest.json"))}
    readme = (PKG / "data" / "README.md").read_text(encoding="utf-8")
    for key in ("checkpoint_sha256", "probe_sha256"):
        vals = {d[key] for d in deps.values()}
        check(len(deps) == 4 and len(vals) == 1, f"all four studies record the same {key}", str(vals))
        check(len(vals) == 1 and next(iter(vals)) in readme, f"data/README.md states the recorded {key}")


def manifest() -> None:
    p = PKG / "RELEASE_MANIFEST.json"
    check(p.is_file(), "RELEASE_MANIFEST.json exists", "run scripts/build_release_manifest.py")
    if not p.is_file():
        return
    m = json.loads(p.read_text(encoding="utf-8"))
    listed = {e["path"]: e["sha256"] for e in m["files"]}
    actual = {str(f.relative_to(PKG)): sha256(f) for f in release_files()}
    check(set(listed) == set(actual), "release manifest lists exactly the package files outside logs/",
          f"unlisted {sorted(set(actual) - set(listed))}; missing {sorted(set(listed) - set(actual))}")
    changed = sorted(k for k in set(listed) & set(actual) if listed[k] != actual[k])
    check(not changed, "every file matches its release-manifest hash", str(changed))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pdf-text", action="store_true", help="also check the PDF text (requires pymupdf)")
    a = ap.parse_args()
    tex_and_build()
    if a.pdf_text:
        pdf_text()
    docs()
    verdict()
    prose_numbers()
    dependencies()
    manifest()
    for x in passes:
        print("PASS", x)
    for x in failures:
        print("FAIL", x)
    print(f"\n{len(passes)} passed, {len(failures)} failed")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
